-- Old links such as /item/3 must keep opening the same item. v1 ids are 1,3,4,5,6 (gaps), so repo items take the same ids.
alter table repo.items alter column id set generated by default;
do $$ declare r record; begin
  for r in select c.conname, c.conrelid::regclass as tbl, a.attname as col
           from pg_constraint c join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
           where c.contype = 'f' and c.confrelid = 'repo.items'::regclass loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
    execute format('alter table %s add constraint %I foreign key (%I) references repo.items(id) on delete cascade on update cascade', r.tbl, r.conname, r.col);
  end loop;
end $$;
-- move to the v1 id, highest first so no id collides on the way
do $$ declare r record; begin
  for r in select id as cur, (metadata->>'v1_id')::bigint as v1 from repo.items where metadata ? 'v1_id' and id <> (metadata->>'v1_id')::bigint
           order by (metadata->>'v1_id')::bigint desc loop
    update repo.items set id = r.v1 where id = r.cur;
  end loop;
end $$;
select setval(pg_get_serial_sequence('repo.items','id'), greatest((select max(id) from repo.items), (select coalesce(max(id),1) from public.items)));
-- counters: use the real v1 numbers (visits made while testing the new pages are not counted)
update repo.item_stats s set views = coalesce(p.views,0), downloads = coalesce(p.downloads,0)
  from repo.items i join public.items p on p.id = (i.metadata->>'v1_id')::bigint where s.item_id = i.id;
