function norm(s: string) {
  return String(s || '')
    .replace(/[\u064B-\u0652\u0670\u0640]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[^\u0621-\u064Aa-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .toLowerCase();
}

// Pick the sections the question is about. The whole pack never goes into one request:
// only the core facts plus the best-matching sections, up to a character cap that keeps
// a question inside the free plan's token budget.
export function knowledgeFor(question: string, maxChars = 2000): string {
  const q = norm(question);
  const scored = SECTIONS
    .map((s) => ({ s, n: s.keys.filter((k) => q.includes(norm(k))).length }))
    .filter((x) => x.n > 0)
    .sort((a, b) => b.n - a.n);
  let out = CORE;
  for (const { s } of scored) {
    if ((out.length + s.body.length + 2) > maxChars) continue;
    out += '\n' + s.body;
  }
  return out;
}
